package cn.coostack.cooparticlesapi.cparticle.path

/**
 * # 路径播放进度的映射方式
 *
 * 决定归一化播放参数 `tau` 如何映射到曲线长度。两种方式都只影响“位置沿路径推进的快慢”，
 * 不改变路径几何，也不改变粒子寿命。
 *
 * [wireValue] 属于 GPU/CPU 共用的 Command ABI，不能按枚举顺序重新编号。
 */
enum class CParticlePathProgressMode(
    /** 写入 Command 参数的数值标识。 */
    val wireValue: Int,
) {
    /**
     * 参数均匀：`tau` 在整条曲线的**参数域**上均匀推进。
     *
     * 也就是每段获得相同的参数区间，无论各段实际长短。分段长度差异大时，粒子在长段上
     * 看起来更快、在短段上更慢。贝塞尔求值只需要参数，不需要弧长表，成本最低。
     */
    PARAMETER(0),

    /**
     * 弧长均匀：`tau` 映射到归一化**弧长**，粒子沿路径以恒定路程速度前进。
     *
     * 实现依赖预采样表的累计弦长，因此分段长度差异再大也不会改变视觉速度。
     * 弧长查找只做一次预采样下标定位与一次线性插值，不逐粒子遍历路径。
     */
    ARC_LENGTH(1),
}
